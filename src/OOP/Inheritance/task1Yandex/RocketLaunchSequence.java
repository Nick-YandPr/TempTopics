package OOP.Inheritance.task1Yandex;

/**
 * Интерфейс, описывающий каноническую процедуру запуска ракеты.
 * Все методы вызываются в строгой последовательности — как на настоящем космодроме,
 * только чуть веселее.
 */
public interface RocketLaunchSequence {

    /**
     * Проверка всех систем перед стартом.
     * Без этого этапа ракета может решить, что она не ракета, а тыква.
     */
    void preLaunchCheck();

    /**
     * Продувка магистралей и камер сгорания инертным газом.
     * Чтобы там ничего лишнего не горело раньше времени.
     */
    void purge();

    /**
     * Протяжка — отсоединение всех земных кабелей и пуповин.
     * Ракета становится по-настоящему самостоятельной.
     */
    void umbilicalPullOut();

    /**
     * Зажигание! Турбонасосы раскручены, форсунки плюются топливом —
     * момент истины.
     */
    void ignition();

    /**
     * Набор тяги и отрыв от стартового стола.
     * Земля остаётся внизу, орбита — впереди.
     */
    void liftoff();

    /**
     * Запускает всю последовательность по порядку
     */
    void executeLaunchSequence();
}